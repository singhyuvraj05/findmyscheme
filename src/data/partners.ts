// Helper: search partners by district or pincode
export function searchPartners(
  query: string,
  typeFilter: string[],
  healthFilter: string[]
): Partner[] {
  const q = query.toLowerCase().trim();
  return partners.filter((p) => {
    const matchQuery =
      q === "" ||
      p.district.toLowerCase().includes(q) ||
      p.pincode.includes(q) ||
      p.state.toLowerCase().includes(q) ||
      p.name.toLowerCase().includes(q);
    const matchType =
      typeFilter.length === 0 || typeFilter.includes(p.type);
    const matchHealth =
      healthFilter.length === 0 || healthFilter.includes(p.fundHealth);
    return matchQuery && matchType && matchHealth;
  });
}

// Get top N recommended (active + highest rating, sorted)
export function getTopPartners(n = 3): Partner[] {
  return [...partners]
    .filter((p) => p.fundHealth === "active")
    .sort((a, b) => b.rating - a.rating)
    .slice(0, n);
}
